import path from 'node:path';
import {createHash} from 'node:crypto';

export function sdkContainerOption(engine = 'docker') {
  if (!['docker', 'podman'].includes(engine)) throw Error('Unsupported SDK container engine');
  return `--container-engine=${engine}`;
}

export function sdkBuildJobs(value = 4) {
  if (!/^(?:[1-9]|[12][0-9]|3[0-2])$/.test(String(value))) throw Error('Invalid SDK job count');
  return Number(value);
}

// Proton configure options for one target. x86_64 keeps its existing command.
export function sdkConfigureArgs({name, engine, sdk, arch = 'x86_64', variant}) {
  if(variant!==undefined&&variant!=='nexus-cachyos')throw Error('Unsupported runtime variant');
  if(variant&&arch!=='x86_64')throw Error('Unreviewed variant architecture');
  if (!['x86_64', 'arm64'].includes(arch)) throw Error('Unsupported target architecture');
  return [`--build-name=${name}`, `--container-engine=${engine}`, `--proton-sdk-image=${sdk}`, '--enable-ccache', ...(arch === 'x86_64' ? [] : [`--target-arch=${arch}`]),...(variant?['--without-nvidia-libs','--without-zluda-libs=all','--without-extras=all','--without-vklayers=all']:[])];
}

export function verifySdkResumeMakefile(text, {source, name, sdk, engine, arch = 'x86_64', variant, rootless = 1}) {
  if(rootless!==0&&rootless!==1)throw Error('Invalid validated SDK container mode');
  const expected = `# Generated by: ${source}/configure.sh ${sdkConfigureArgs({name, engine, sdk, arch, variant}).join(' ')}\n\nSRCDIR     := ${source}\nBUILD_NAME := ${name}\nTARGET_ARCH := ${arch}\nINTERNAL_TOOL_NAME := ${name}-proton\nSTEAMRT_IMAGE := ${sdk}\nROOTLESS_CONTAINER := ${rootless}\nCONTAINER_ENGINE := ${engine}\nENABLE_CCACHE := 1\n${variant?'WITHOUT_NVIDIA_LIBS := 1\nWITHOUT_ZLUDA_LIBS := 1\nWITHOUT_EXTRAS := 1\nWITHOUT_VKLAYERS := 1\nHOST_CFLAGS := -O2 -march=nocona -mtune=core-avx2\nHOST_RUSTFLAGS := -Copt-level=3 -Ctarget-cpu=nocona\n':''}\ninclude $(SRCDIR)/Makefile.in\n`;
  if (text !== expected) throw Error('Resume requires the exact existing pinned SDK configuration');
}

export function captureSdkConfiguration(text, options){
  const matches=[...text.matchAll(/^ROOTLESS_CONTAINER := ([01])$/gm)];
  if(matches.length!==1)throw Error('Generated SDK configuration must declare one valid container mode');
  const rootless=Number(matches[0][1]);
  verifySdkResumeMakefile(text,{...options,rootless});
  return Object.freeze({rootless,sha256:createHash('sha256').update(text).digest('hex')});
}
export function verifyPreparedSdkConfiguration(text, options, state){
  if(!state||![0,1].includes(state.rootless)||!/^[a-f0-9]{64}$/.test(state.sha256))throw Error('Missing validated SDK configuration state');
  verifySdkResumeMakefile(text,{...options,rootless:state.rootless});
  if(createHash('sha256').update(text).digest('hex')!==state.sha256)throw Error('Prepared SDK configuration changed');
}

export function sdkBuildPlan(build, epoch, jobs = 4, redist, hostTools = 'x86_64', xml2Source) {
  if (!path.isAbsolute(build) || !/^[0-9]+$/.test(epoch) || !['x86_64', 'aarch64'].includes(hostTools)) throw Error('Invalid SDK build inputs');
  if (redist !== undefined && (!path.isAbsolute(redist) || path.dirname(redist) !== build || !/^redist-[a-f0-9]{8}$/.test(path.basename(redist)))) throw Error('Invalid isolated redistribution path');
  if(xml2Source!==undefined&&xml2Source!==path.join(path.dirname(build),'xgr-xml2-source'))throw Error('XML source must be the verified prepared directory');
  const count = sdkBuildJobs(jobs);
  const common = [`-j${count}`, `J=${count}`, `SOURCE_DATE_EPOCH=${epoch}`,...(xml2Source?[`NEXUS_XML2_SOURCE=${xml2Source}`]:[])];
  return [
    // Proton module64 does not depend on its host-tools stamp. A clean parallel
    // module build can otherwise launch a second WIDL make in the same tree.
    {name: 'Build shared Wine host tools before module submakes', args: [...common, path.join(build, `.wine-${hostTools}-tools`)], timeout: 60*60*1000},
    {name: 'Check xgameruntime in every SDK PE architecture', args: [...common, 'module=xgameruntime', 'module'], timeout: 60*60*1000},
    {name: 'Build complete coherent Proton redistribution', args: [...common, ...(redist ? [`REDIST_DIR=${redist}`] : []), 'redist'], timeout: 5*60*60*1000},
  ];
}
