import {test} from 'node:test';
import assert from 'node:assert/strict';
import {sdkConfigureArgs,verifySdkResumeMakefile} from './sdk-build-plan.mjs';
test('conservative CachyOS configuration excludes optional vendor stacks and wow64',()=>{
  const args=sdkConfigureArgs({name:'test',engine:'podman',sdk:'sdk@sha256:123',variant:'nexus-cachyos'});
  for(const arg of ['--without-nvidia-libs','--without-zluda-libs=all','--without-extras=all','--without-vklayers=all'])assert.ok(args.includes(arg));
  assert.ok(!args.includes('--enable-wow64'));
  assert.throws(()=>sdkConfigureArgs({variant:'nexus-cachyos',arch:'arm64'}));
  assert.throws(()=>sdkConfigureArgs({variant:'unknown'}));
});
test('CachyOS resume accepts only its exact conservative configuration',()=>{
 const options={source:'/source',name:'variant',sdk:'sdk',engine:'podman',variant:'nexus-cachyos'};
 const text=`# Generated by: /source/configure.sh ${sdkConfigureArgs(options).join(' ')}\n\nSRCDIR     := /source\nBUILD_NAME := variant\nTARGET_ARCH := x86_64\nINTERNAL_TOOL_NAME := variant-proton\nSTEAMRT_IMAGE := sdk\nROOTLESS_CONTAINER := 1\nCONTAINER_ENGINE := podman\nENABLE_CCACHE := 1\nWITHOUT_NVIDIA_LIBS := 1\nWITHOUT_ZLUDA_LIBS := 1\nWITHOUT_EXTRAS := 1\nWITHOUT_VKLAYERS := 1\nHOST_CFLAGS := -O2 -march=nocona -mtune=core-avx2\nHOST_RUSTFLAGS := -Copt-level=3 -Ctarget-cpu=nocona\n\ninclude $(SRCDIR)/Makefile.in\n`;
 verifySdkResumeMakefile(text,options);
 assert.throws(()=>verifySdkResumeMakefile(text.replace('WITHOUT_EXTRAS := 1','WITHOUT_EXTRAS := 0'),options));
});
