import {test} from 'node:test';
import assert from 'node:assert/strict';
import {sdkConfigureArgs,verifySdkResumeMakefile} from './sdk-build-plan.mjs';
const optOuts=['--without-nvidia-libs','--without-zluda-libs=all','--without-extras=all','--without-vklayers=all'];
const options={source:'/source',name:'variant',sdk:'sdk',engine:'podman',variant:'nexus-cachyos'};
const fullMakefile=()=>`# Generated by: /source/configure.sh ${sdkConfigureArgs(options).join(' ')}\n\nSRCDIR     := /source\nBUILD_NAME := variant\nTARGET_ARCH := x86_64\nINTERNAL_TOOL_NAME := variant-proton\nSTEAMRT_IMAGE := sdk\nROOTLESS_CONTAINER := 1\nCONTAINER_ENGINE := podman\nENABLE_CCACHE := 1\nHOST_CFLAGS := -O2 -march=nocona -mtune=core-avx2\nHOST_RUSTFLAGS := -Copt-level=3 -Ctarget-cpu=nocona\n\ninclude $(SRCDIR)/Makefile.in\n`;
// The former reduced configuration passed four WITHOUT_* opt-outs.
const reducedMakefile=()=>fullMakefile().replace('HOST_CFLAGS','WITHOUT_NVIDIA_LIBS := 1\nWITHOUT_ZLUDA_LIBS := 1\nWITHOUT_EXTRAS := 1\nWITHOUT_VKLAYERS := 1\nHOST_CFLAGS');
test('CachyOS variant keeps the pinned upstream component set without opt-outs',()=>{
 const args=sdkConfigureArgs(options);
 for(const arg of optOuts)assert.equal(args.includes(arg),false,arg);
 assert.ok(!args.some(arg=>arg.startsWith('--without-')),'no WITHOUT_* opt-out may be passed');
 assert.ok(!args.includes('--enable-wow64'));
 assert.throws(()=>sdkConfigureArgs({variant:'nexus-cachyos',arch:'arm64'}));
 assert.throws(()=>sdkConfigureArgs({variant:'unknown'}));
});
test('CachyOS resume accepts only the full pinned configuration and rejects the reduced one',()=>{
 const full=fullMakefile();
 verifySdkResumeMakefile(full,options);
 const reduced=reducedMakefile();
 assert.ok(reduced.includes('WITHOUT_EXTRAS := 1'));
 for(const line of ['WITHOUT_NVIDIA_LIBS := 1','WITHOUT_ZLUDA_LIBS := 1','WITHOUT_EXTRAS := 1','WITHOUT_VKLAYERS := 1'])assert.ok(reduced.includes(line),line);
 assert.throws(()=>verifySdkResumeMakefile(reduced,options));
 assert.throws(()=>verifySdkResumeMakefile(full.replace('HOST_CFLAGS','WITHOUT_EXTRAS := all\nHOST_CFLAGS'),options));
 assert.throws(()=>verifySdkResumeMakefile(full.replace('HOST_CFLAGS := -O2','HOST_CFLAGS := -O3'),options));
 // The undefined-variant (Standard) expectation is unchanged and rejects this text.
 assert.throws(()=>verifySdkResumeMakefile(full,{...options,variant:undefined}));
});
